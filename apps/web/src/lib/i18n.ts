export function localeFromCookie(value: string | undefined | null): Locale {
  return value === "en" ? "en" : "sk";
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const template = (locale === "en" ? en : sk)[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function auditTypeLabel(locale: Locale, type: string) {
  const key = `auditType.${type}` as MessageKey;
  if (key in sk) return t(locale, key);
  return type;
}

export function statusLabel(locale: Locale, status: string) {
  const key = `status.${status}` as MessageKey;
  if (key in sk) return t(locale, key);
  return status;
}
